export type Heading = { id: string; text: string; level: 2 | 3 };

export type PreparedBlock = Block & { id?: string };

/**
 * Проставляє заголовкам якорі й одразу збирає з них зміст.
 *
 * Обидва списки робляться за один прохід навмисно: якби зміст і текст
 * рахували якорі окремо, при однакових заголовках вони розійшлися б,
 * і посилання вели б не туди.
 */
export function prepare(body: readonly Block[]): { blocks: PreparedBlock[]; toc: Heading[] } {
  const blocks: PreparedBlock[] = [];
  const toc: Heading[] = [];
  const used = new Map<string, number>();

  for (const block of body) {
    if (block.type !== "h2" && block.type !== "h3" && block.type !== "h4") {
      blocks.push(block);
      continue;
    }

    const base = slugify(block.text) || "rozdil";
    const seen = used.get(base) ?? 0;
    used.set(base, seen + 1);
    const id = seen === 0 ? base : `${base}-${seen + 1}`;

    blocks.push({ ...block, id });

    // h4 у зміст не беремо: він потрібен усередині розділу, а в
    // навігації робить із трьох пунктів дванадцять.
    if (block.type !== "h4") {
      toc.push({ id, text: block.text, level: block.type === "h2" ? 2 : 3 });
    }
  }

  return { blocks, toc };
}

export function getArticle(slug: string): Article | undefined {
  return articles.find((article) => article.slug === slug);
}

/** Спершу статті зі спільними темами, далі — просто свіжі. */
export function relatedArticles(slug: string, limit = 3): Article[] {
  const current = getArticle(slug);
  if (!current) return [];

  return articles
    .filter((article) => article.slug !== slug)
    .map((article) => ({
      article,
      shared: article.tags.filter((tag) => current.tags.includes(tag)).length,
    }))
    .sort((a, b) => b.shared - a.shared || b.article.date.localeCompare(a.article.date))
    .slice(0, limit)
    .map((entry) => entry.article);
}

export const allTags: string[] = [...new Set(articles.flatMap((article) => article.tags))].sort(
  (a, b) => a.localeCompare(b, "uk"),
);

